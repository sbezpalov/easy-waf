func TestDefaultManifestOrder(t *testing.T) {
	want := []string{
		"document-before-tokens.html",
		"styles/tokens.css",
		"styles/application.css",
		"document-before-screens.html",
		"screens/dashboard.html",
		"screens/applications.html",
		"screens/certificates.html",
		"document-after-certificates.html",
	}
	if got := DefaultManifest(); !slices.Equal(got, want) {
		t.Fatalf("default manifest order %q, want %q", got, want)
	}
}

func TestDefaultBuildMatchesCommittedBundle(t *testing.T) {
	got, err := Build(os.DirFS("../src"), DefaultManifest())
	if err != nil {
		t.Fatal(err)
	}
	want, err := os.ReadFile("../dist/index.html")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("generated web UI differs from committed dist/index.html; run go generate ./internal/webui")
	}
}

func TestBuildUsesManifestOrderAndNormalizesNewlines(t *testing.T) {
	source := fstest.MapFS{
		"first":  {Data: []byte("first\r\n")},
		"second": {Data: []byte("second\rthird\n")},
	}
	got, err := Build(source, []string{"second", "first"})
	if err != nil {
		t.Fatal(err)
	}
	if want := []byte("second\nthird\nfirst\n"); !bytes.Equal(got, want) {
		t.Fatalf("generated bytes %q, want %q", got, want)
	}
}

func TestWriteDefaultCreatesAndRepairsBundle(t *testing.T) {
	root := t.TempDir()
	source := filepath.Join(root, "src")
	for name, data := range map[string]string{
		"document-before-tokens.html":      "before\r\n",
		"styles/tokens.css":                "tokens\r",
		"styles/application.css":           "styles\r\n",
		"document-before-screens.html":     "shell\n",
		"screens/dashboard.html":           "dashboard\r",
		"screens/applications.html":        "applications\n",
		"screens/certificates.html":        "certificates\r\n",
		"document-after-certificates.html": "after\n",
	} {
		filename := filepath.Join(source, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(filename), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filename, []byte(data), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	output := filepath.Join(root, "index.html")
	if err := WriteDefault(source, output); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(output, []byte("stale"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := WriteDefault(source, output); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(output)
	if err != nil {
		t.Fatal(err)
	}
	if want := []byte("before\ntokens\nstyles\nshell\ndashboard\napplications\ncertificates\nafter\n"); !bytes.Equal(got, want) {
		t.Fatalf("generated bytes %q, want %q", got, want)
	}
}

func TestBuildRejectsInvalidSourceLayout(t *testing.T) {
	tests := []struct {
		name     string
		source   fstest.MapFS
		manifest []string
	}{
		{name: "empty manifest", source: fstest.MapFS{}},
		{name: "invalid path", source: fstest.MapFS{}, manifest: []string{"../outside"}},
		{name: "duplicate", source: fstest.MapFS{"part": {Data: []byte("x")}}, manifest: []string{"part", "part"}},
		{name: "missing", source: fstest.MapFS{}, manifest: []string{"part"}},
		{
			name: "unexpected",
			source: fstest.MapFS{
				"part":  {Data: []byte("x")},
				"extra": {Data: []byte("y")},
			},
			manifest: []string{"part"},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			if _, err := Build(test.source, test.manifest); err == nil {
				t.Fatal("Build succeeded for an invalid source layout")
			}
		})
	}
}
