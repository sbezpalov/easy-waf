func TestDefaultBuildMatchesCommittedBundle(t *testing.T) {
	got, err := Build(os.DirFS("../src"), DefaultManifest())
	if err != nil {
		t.Fatal(err)
	}
	want, err := os.ReadFile("../dist/index.html")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("generated web UI differs from committed dist/index.html; run go generate ./internal/webui")
	}
}

func TestDefaultBuildKeepsSinglePlainScriptBlock(t *testing.T) {
	page, err := Build(os.DirFS("../src"), DefaultManifest())
	if err != nil {
		t.Fatal(err)
	}
	if got := bytes.Count(page, []byte("<script>")); got != 1 {
		t.Fatalf("generated page has %d plain script openings, want 1", got)
	}
	if got := bytes.Count(page, []byte("</script>")); got != 1 {
		t.Fatalf("generated page has %d script closings, want 1", got)
	}
	for _, name := range []string{
		"application-before-renderers.js",
		"renderers.js",
		"application.js",
	} {
		script, err := os.ReadFile(filepath.Join("../src/scripts", name))
		if err != nil {
			t.Fatal(err)
		}
		if bytes.Contains(script, []byte("<script")) || bytes.Contains(script, []byte("</script>")) {
			t.Fatalf("JavaScript source %q must not own its inline script wrapper", name)
		}
	}
}

func TestBuildUsesManifestOrderAndNormalizesNewlines(t *testing.T) {
	source := fstest.MapFS{
		"first":  {Data: []byte("first\r\n")},
		"second": {Data: []byte("second\rthird\n")},
	}
	got, err := Build(source, []string{"second", "first"})
	if err != nil {
		t.Fatal(err)
	}
	if want := []byte("second\nthird\nfirst\n"); !bytes.Equal(got, want) {
		t.Fatalf("generated bytes %q, want %q", got, want)
	}
}

func TestWriteDefaultCreatesAndRepairsBundle(t *testing.T) {
	root := t.TempDir()
	source := filepath.Join(root, "src")
	for name, data := range map[string]string{
		"document-before-tokens.html":             "before\r\n",
		"styles/tokens.css":                       "tokens\r",
		"styles/application.css":                  "styles\r\n",
		"document-before-screens.html":            "shell\n",
		"screens/dashboard.html":                  "dashboard\r",
		"screens/applications.html":               "applications\n",
		"screens/certificates.html":               "certificates\r\n",
		"screens/security.html":                   "security\r",
		"screens/crowdsec.html":                   "crowdsec\n",
		"screens/fail2ban.html":                   "fail2ban\r\n",
		"screens/system.html":                     "system\r",
		"screens/network.html":                    "network\n",
		"screens/users.html":                      "users\r\n",
		"screens/edge-changes.html":               "edge changes\r",
		"screens/settings.html":                   "settings\n",
		"screens/events-audit.html":               "events\r\n",
		"document-before-script.html":             "before script\r",
		"scripts/application-before-renderers.js": "application before renderers\n",
		"scripts/renderers.js":                    "renderers\r",
		"scripts/application.js":                  "application script\n",
		"document-after-script.html":              "after script\r\n",
	} {
		filename := filepath.Join(source, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(filename), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filename, []byte(data), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	output := filepath.Join(root, "index.html")
	if err := WriteDefault(source, output); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(output, []byte("stale"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := WriteDefault(source, output); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(output)
	if err != nil {
		t.Fatal(err)
	}
	if want := []byte("before\ntokens\nstyles\nshell\ndashboard\napplications\ncertificates\nsecurity\ncrowdsec\nfail2ban\nsystem\nnetwork\nusers\nedge changes\nsettings\nevents\nbefore script\napplication before renderers\nrenderers\napplication script\nafter script\n"); !bytes.Equal(got, want) {
		t.Fatalf("generated bytes %q, want %q", got, want)
	}
}

func TestBuildRejectsInvalidSourceLayout(t *testing.T) {
	tests := []struct {
		name     string
		source   fstest.MapFS
		manifest []string
	}{
		{name: "empty manifest", source: fstest.MapFS{}},
		{name: "invalid path", source: fstest.MapFS{}, manifest: []string{"../outside"}},
		{name: "duplicate", source: fstest.MapFS{"part": {Data: []byte("x")}}, manifest: []string{"part", "part"}},
		{name: "missing", source: fstest.MapFS{}, manifest: []string{"part"}},
		{
			name: "unexpected",
			source: fstest.MapFS{
				"part":  {Data: []byte("x")},
				"extra": {Data: []byte("y")},
			},
			manifest: []string{"part"},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			if _, err := Build(test.source, test.manifest); err == nil {
				t.Fatal("Build succeeded for an invalid source layout")
			}
		})
	}
}
